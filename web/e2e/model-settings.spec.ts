import {test,expect,type Page} from '@playwright/test'
async function enter(page:Page){await page.goto('/');await page.getByRole('button',{name:'先体验演示版'}).click()}
async function open(page:Page){
 await page.getByRole('button',{name:'设置',exact:true}).click()
 await expect(page.getByLabel('API Key',{exact:true})).toHaveCount(0)
 await expect(page.getByLabel('HTTPS 接口地址')).toHaveCount(0)
 await expect(page.getByRole('button',{name:'刷新任务',exact:true})).toHaveCount(0)
 await page.screenshot({path:'/tmp/qingji-settings-arco-desktop.png',animations:'disabled'})
 const settingsWidth=(await page.getByRole('dialog',{name:'设置',exact:true}).boundingBox())!.width
 await page.getByRole('button',{name:'模型配置',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'模型配置',exact:true})).toBeVisible()
 expect((await page.getByRole('dialog',{name:'模型配置',exact:true}).boundingBox())!.width).toBe(settingsWidth)
}
test('simplified model configuration automatically persists edits across tabs and restarts',async({page,context,browser})=>{
 await enter(page);await open(page)
 const dialog=page.getByRole('dialog',{name:'模型配置',exact:true})
 await expect(dialog).not.toContainText('YOUR MODEL, YOUR CONTROL')
 for(const name of ['保存模型配置','清除保存的配置'])await expect(dialog.getByRole('button',{name,exact:true})).toHaveCount(0)
 await expect(dialog.getByRole('checkbox')).toHaveCount(0)
 await expect(dialog).not.toContainText('仅在本机按账号保存')
 await page.getByLabel('HTTPS 接口地址').fill('https://model.example/v1/chat/completions')
 await page.getByLabel('模型名称').fill('remembered-model')
 await page.getByLabel('API Key',{exact:true}).fill('fake-remembered-key')
 await expect(page.getByLabel('API Key',{exact:true})).toHaveAttribute('type','password')
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('qingji.vue.model.v1.demo')||'{}').model)).toBe('remembered-model')
 await page.getByRole('button',{name:'关闭弹窗',exact:true}).click()
 await expect(page.locator('.composer-model')).toHaveText('remembered-model')
 const second=await context.newPage();await enter(second);await open(second)
 await expect(second.getByLabel('模型名称')).toHaveValue('remembered-model')
 await expect(second.getByLabel('API Key',{exact:true})).toHaveValue('fake-remembered-key')
 await second.getByLabel('API Key',{exact:true}).fill('changed-key')
 await second.getByRole('button',{name:'返回设置',exact:false}).click()
 await second.getByRole('button',{name:'模型配置',exact:true}).click()
 await expect(second.getByLabel('API Key',{exact:true})).toHaveValue('changed-key')
 const restarted=await browser.newContext({storageState:await context.storageState()})
 const third=await restarted.newPage();await enter(third);await open(third)
 await expect(third.getByLabel('API Key',{exact:true})).toHaveValue('changed-key')
 await third.screenshot({path:'/tmp/qingji-model-settings-desktop.png',fullPage:true})
 await third.setViewportSize({width:390,height:844})
 expect(await third.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await third.screenshot({path:'/tmp/qingji-model-settings-mobile.png',fullPage:true})
 await third.getByRole('button',{name:'返回设置',exact:true}).click()
 await third.screenshot({path:'/tmp/qingji-settings-arco-mobile.png',fullPage:true})
 await restarted.close()
 await second.getByLabel('API Key',{exact:true}).fill('')
 await second.getByRole('button',{name:'关闭弹窗'}).click()
 await second.reload();await second.getByRole('button',{name:'先体验演示版'}).click();await open(second)
 await expect(second.getByLabel('API Key',{exact:true})).toBeEmpty()
})

test('automatic model saving rejects invalid endpoints and reports storage failures',async({page})=>{
 await enter(page);await open(page)
 await page.getByLabel('HTTPS 接口地址').fill('http://invalid.example')
 await page.getByRole('button',{name:'关闭弹窗',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'模型配置',exact:true})).toBeVisible()
 expect(await page.evaluate(()=>localStorage.getItem('qingji.vue.model.v1.demo'))).toBeNull()
 await page.getByLabel('HTTPS 接口地址').fill('https://model.example/v1/chat/completions')
 await page.evaluate(()=>{const original=Storage.prototype.setItem;Storage.prototype.setItem=function(key,value){if(key.startsWith('qingji.vue.model.'))throw Error('blocked');original.call(this,key,value)}})
 await page.getByLabel('模型名称').fill('unsaved-model')
 await page.getByRole('button',{name:'关闭弹窗',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'模型配置',exact:true})).toBeVisible()
 await expect(page.getByRole('status')).toContainText('配置保存失败')
 await expect(page.getByLabel('模型名称')).toHaveValue('unsaved-model')
})
