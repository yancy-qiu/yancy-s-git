import {test,expect,type Page} from '@playwright/test'
async function enter(page:Page){await page.goto('/');await page.getByRole('button',{name:'先体验演示版'}).click()}
async function open(page:Page){
 await page.getByRole('button',{name:'设置',exact:true}).click()
 await expect(page.getByLabel('API Key',{exact:true})).toHaveCount(0)
 await expect(page.getByLabel('HTTPS 接口地址')).toHaveCount(0)
 await page.getByRole('button',{name:'模型配置 →',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'模型配置',exact:true})).toBeVisible()
}
test('separate configuration remembers across new tabs and restart, supports forgetting and cancel',async({page,context,browser})=>{
 await enter(page);await open(page)
 await page.getByLabel('HTTPS 接口地址').fill('https://model.example/v1/chat/completions')
 await page.getByLabel('模型名称').fill('remembered-model')
 await page.getByLabel('API Key',{exact:true}).fill('fake-remembered-key')
 await expect(page.getByLabel('API Key',{exact:true})).toHaveAttribute('type','password')
 await page.getByRole('button',{name:'保存模型配置',exact:true}).click()
 const second=await context.newPage();await enter(second);await open(second)
 await expect(second.getByLabel('模型名称')).toHaveValue('remembered-model')
 await expect(second.getByLabel('API Key',{exact:true})).toHaveValue('fake-remembered-key')
 await second.getByLabel('API Key',{exact:true}).fill('unsaved-change')
 await second.getByRole('button',{name:'返回设置',exact:false}).click()
 await expect(second.getByLabel('API Key',{exact:true})).toHaveCount(0)
 await second.getByRole('button',{name:'模型配置 →',exact:true}).click()
 await expect(second.getByLabel('API Key',{exact:true})).toHaveValue('fake-remembered-key')
 const restarted=await browser.newContext({storageState:await context.storageState()})
 const third=await restarted.newPage();await enter(third);await open(third)
 await expect(third.getByLabel('API Key',{exact:true})).toHaveValue('fake-remembered-key')
 await third.setViewportSize({width:390,height:844})
 expect(await third.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await third.screenshot({path:'/tmp/qingji-model-settings-mobile.png',fullPage:true})
 await restarted.close()
 await second.getByRole('button',{name:'清除保存的配置',exact:true}).click()
 await expect(second.getByLabel('API Key',{exact:true})).toBeEmpty()
 await second.getByRole('button',{name:'关闭弹窗'}).click()
 await second.reload();await second.getByRole('button',{name:'先体验演示版'}).click();await open(second)
 await expect(second.getByLabel('API Key',{exact:true})).toBeEmpty()
 await second.getByLabel('模型名称').fill('temporary-model')
 await second.getByLabel('API Key',{exact:true}).fill('temporary-key')
 await second.getByLabel('在此浏览器记住配置').uncheck()
 await second.getByRole('button',{name:'保存模型配置',exact:true}).click()
 await second.reload();await second.getByRole('button',{name:'先体验演示版'}).click();await open(second)
 await expect(second.getByLabel('API Key',{exact:true})).toBeEmpty()
})
