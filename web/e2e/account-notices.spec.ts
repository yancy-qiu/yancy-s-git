import {test,expect} from '@playwright/test'
test('account controls replace the header and widget, with automatic notices and timed undo',async({page})=>{
 await page.clock.install()
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('/');await page.getByRole('button',{name:'先体验演示版'}).click()
 await expect(page.locator('.topbar,.widget,.sync-note')).toHaveCount(0)
 await expect(page.getByRole('button',{name:'小组件预览',exact:true})).toHaveCount(0)
 const account=page.locator('.sidebar-bottom')
 await expect(account).toContainText('演示账号')
 expect((await account.boundingBox())!.y).toBeGreaterThan(800)
 await account.getByRole('button',{name:'设置',exact:true}).click()
 await expect(page.getByRole('dialog')).not.toContainText('小组件')
 await page.getByRole('button',{name:'保存设置',exact:true}).click()
 await expect(page.locator('.toast')).toHaveText('设置已保存')
 await expect(page.getByRole('button',{name:'关闭提示',exact:true})).toHaveCount(0)
 await page.clock.runFor(2000)
 await account.getByRole('button',{name:'设置',exact:true}).click();await page.getByRole('button',{name:'保存设置',exact:true}).click()
 await page.clock.runFor(2000);await expect(page.locator('.toast')).toHaveText('设置已保存')
 await page.clock.runFor(1100);await expect(page.locator('.toast')).toHaveCount(0)
 await page.getByRole('button',{name:'查看：给今天留一点清晰',exact:true}).click();await page.getByRole('button',{name:'删除记录',exact:true}).click()
 await page.clock.runFor(3100);await expect(page.getByRole('button',{name:'撤销',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'撤销',exact:true}).click();await expect(page.getByRole('button',{name:'查看：给今天留一点清晰',exact:true})).toBeVisible()
 await page.clock.runFor(3100);await expect(page.locator('.toast')).toHaveCount(0)
 await page.getByRole('button',{name:'查看：给今天留一点清晰',exact:true}).click();await page.getByRole('button',{name:'删除记录',exact:true}).click();await page.clock.runFor(6100);await expect(page.locator('.toast')).toHaveCount(0)
 await page.screenshot({path:'/tmp/qingji-account-desktop.png',animations:'disabled'})
 await page.setViewportSize({width:390,height:844});await page.getByRole('button',{name:'个人中心',exact:true}).click()
 await expect(page.getByRole('button',{name:'设置',exact:true})).toBeVisible()
 await page.screenshot({path:'/tmp/qingji-account-mobile.png',animations:'disabled'})
 await page.getByRole('button',{name:'退出演示',exact:true}).click();await expect(page.getByRole('button',{name:'先体验演示版'})).toBeVisible()
})
